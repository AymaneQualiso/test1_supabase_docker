-- updated_at trigger: Postgres does not update it on its own
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.companies (
  id          bigint generated by default as identity primary key,
  label       varchar(150) not null,
  abv         text,
  ice         varchar(15),
  city        varchar(100),
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create trigger companies_set_updated_at
before update on public.companies
for each row execute function public.set_updated_at();

create table public.societe_marques (
  id          bigint generated by default as identity primary key,
  libelle     varchar(150) not null,
  company_id  bigint not null references public.companies(id) on delete restrict,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create unique index societe_marques_company_libelle_unique
  on public.societe_marques (company_id, lower(libelle))
  where deleted_at is null;

create trigger societe_marques_set_updated_at
before update on public.societe_marques
for each row execute function public.set_updated_at();

create table public.car_statuses (
  id          bigint generated by default as identity primary key,
  label       varchar(150) not null unique,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create trigger car_statuses_set_updated_at
before update on public.car_statuses
for each row execute function public.set_updated_at();


create table public.cars (
  id                 bigint generated by default as identity primary key,
  immat              varchar(20) not null,
  num_chassis        varchar(50),
  couleur            varchar(50),
  achat_societe_id   bigint references public.companies(id)       on delete set null,
  societe_marque_id  bigint references public.societe_marques(id) on delete set null,
  car_statut_id      bigint references public.car_statuses(id)    on delete restrict,
  km_dernier         numeric(10,2),
  date_mce           date,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  deleted_at         timestamptz
);

create unique index cars_immat_unique on public.cars (immat) where deleted_at is null;
create index cars_achat_societe_id_idx  on public.cars (achat_societe_id);
create index cars_societe_marque_id_idx on public.cars (societe_marque_id);
create index cars_car_statut_id_idx     on public.cars (car_statut_id);

create trigger cars_set_updated_at
before update on public.cars
for each row execute function public.set_updated_at();

-- 1) RLS on all tables, always
alter table public.companies       enable row level security;
alter table public.societe_marques enable row level security;
alter table public.car_statuses    enable row level security;
alter table public.cars            enable row level security;

-- 2) Explicit privileges: read only for week 1
grant select on public.companies, public.societe_marques,
               public.car_statuses, public.cars
  to anon, authenticated;

-- 3) TEMPORARY week 1 policies: read only non-deleted rows
create policy "week1_read" on public.companies       for select using (deleted_at is null);
create policy "week1_read" on public.societe_marques for select using (deleted_at is null);
create policy "week1_read" on public.car_statuses    for select using (true);
create policy "week1_read" on public.cars            for select using (deleted_at is null);